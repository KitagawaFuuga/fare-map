import { describe, expect, it } from "vitest";
import { fareCalcKm } from "@/lib/fare/fare-distance";

// 名鉄は線区ごとに擬制率をかけた「運賃計算キロ」で運賃を決める。
// A線区は営業キロそのまま、B線区は15%増、C線区は25%増。
describe("fareCalcKm", () => {
  it("擬制率をかけて合計し、1km単位に切り上げる", () => {
    // 名鉄名古屋→中部国際空港: 名古屋本線5.8 + (常滑線29.3 + 空港線4.2)×1.15 = 44.325
    expect(
      fareCalcKm([
        { km: 5.8, rate: 1.0 },
        { km: 29.3, rate: 1.15 },
        { km: 4.2, rate: 1.15 },
      ]),
    ).toBe(45);
  });

  it("倍率が1.0だけなら営業キロの切り上げと同じ", () => {
    expect(fareCalcKm([{ km: 27.9, rate: 1.0 }])).toBe(28);
  });

  it("ちょうど整数になるときは切り上げない", () => {
    expect(fareCalcKm([{ km: 10, rate: 1.0 }])).toBe(10);
  });

  // 端数処理を「合計してから切り上げ」にしないと額が変わる。
  // 区間ごとに切り上げると 4.2×1.15=4.83→5 と 17.0×1.15=19.55→20 で計25km、
  // 合計してからだと 21.2×1.15=24.38→25km。太田川→中部国際空港の実額650円は後者
  it("区間ごとではなく合計してから切り上げる", () => {
    expect(
      fareCalcKm([
        { km: 1.4, rate: 1.15 },
        { km: 1.4, rate: 1.15 },
      ]),
    ).toBe(4);
  });

  it("区間が無ければ0", () => {
    expect(fareCalcKm([])).toBe(0);
  });

  it("浮動小数の誤差で余分に切り上げない", () => {
    // 0.1+0.2 が 0.30000000000000004 になる類の誤差で 1km 増えてはいけない
    expect(
      fareCalcKm([
        { km: 0.1, rate: 1.0 },
        { km: 0.2, rate: 1.0 },
        { km: 2.7, rate: 1.0 },
      ]),
    ).toBe(3);
  });
});
