// 区間の距離は駅間キロの足し算なので、足す順番で 15 が 15.000000000000002 になる。
// 運賃表や加算額の表は「15km 以下」のように境目で区切るので、この誤差だけで1つ上の帯になり、
// 往復で運賃が食い違っていた（JR山口線 篠目→地福 240円、地福→篠目 330円）。
// 駅間キロは小数2桁まで（換算キロでも3桁）なので、それより十分細かい桁で丸めて誤差だけを消す
export function withoutFloatNoise(km: number): number {
  return Math.round(km * 1e6) / 1e6;
}
